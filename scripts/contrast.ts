// Checks WCAG 2.2 contrast for every text/background pair the design uses,
// in light and dark, and writes design/contrast.md. Exits 1 if any required
// pair fails. Usage: pnpm contrast
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const css = readFileSync(join(root, "src", "app", "tokens.css"), "utf8");

function block(selector: string): Record<string, string> {
  const start = css.indexOf(`${selector} {`);
  if (start < 0) throw new Error(`selector ${selector} not found in tokens.css`);
  const body = css.slice(start, css.indexOf("}", start));
  return Object.fromEntries([...body.matchAll(/--([\w-]+):\s*(#[0-9a-fA-F]{6})/g)].map((m) => [m[1], m[2]]));
}

const themes = { light: block(":root"), dark: block(".dark") };

const luminance = (hex: string) => {
  const [r = 0, g = 0, b = 0] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
  const lin = (c: number) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
  return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b);
};
const ratio = (a: string, b: string) => {
  const [la, lb] = [luminance(a), luminance(b)];
  return (Math.max(la, lb) + 0.05) / (Math.min(la, lb) + 0.05);
};

// [foreground, background, minimum, what it's used for]
const pairs: [string, string, number, string][] = [
  ["ink", "bg", 4.5, "body text"],
  ["ink", "surface", 4.5, "text on cards"],
  ["ink-2", "bg", 4.5, "lead paragraphs"],
  ["ink-2", "surface", 4.5, "card body text"],
  ["muted", "bg", 4.5, "secondary text, micro-labels"],
  ["muted", "surface", 4.5, "secondary text on cards"],
  ["muted", "surface-2", 4.5, "secondary text on tinted panels"],
  ["bg", "ink", 4.5, "primary button label"],
  ["accent", "bg", 4.5, "accent text / link hover"],
  ["accent", "surface", 4.5, "accent text on cards"],
  ["accent-ink", "accent", 4.5, "text on accent fill"],
  ["ink", "accent-soft", 4.5, "selected text (::selection)"],
  ["ok", "surface", 3, "status dot (UI graphic)"],
  ["accent", "bg", 3, "focus ring (UI graphic)"],
  ["faint", "bg", 0, "decorative only: never text (informational)"],
];

let failed = 0;
let md = "# Contrast report\n\nGenerated by `pnpm contrast` from `src/app/tokens.css`. WCAG 2.2: 4.5:1 for body text, 3:1 for large text and UI graphics.\n\n";
for (const [name, t] of Object.entries(themes)) {
  md += `## ${name}\n\n| Foreground | Background | Ratio | Needs | Result | Used for |\n|---|---|---:|---:|---|---|\n`;
  for (const [fg, bg, min, use] of pairs) {
    const f = t[fg], b = t[bg];
    if (!f || !b) throw new Error(`missing token --${f ? bg : fg} in ${name}`);
    const r = ratio(f, b);
    const pass = r >= min;
    if (!pass) failed++;
    const result = min === 0 ? "n/a" : pass ? "pass" : "**FAIL**";
    md += `| \`--${fg}\` ${f} | \`--${bg}\` ${b} | ${r.toFixed(2)}:1 | ${min ? `${min}:1` : "–"} | ${result} | ${use} |\n`;
  }
  md += "\n";
}
md += "`--faint` is reserved for hairline decoration and the dimmed ends of the hero map (aria-hidden). It is never used for readable text.\n";
writeFileSync(join(root, "design", "contrast.md"), md);
console.log(failed ? `${failed} contrast failure(s), see design/contrast.md` : "all contrast pairs pass");
process.exit(failed ? 1 : 0);
